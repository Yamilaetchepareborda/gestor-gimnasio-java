    private void listarEntrenadores() {
    try {
        List<Entrenador> lista = entrenadorDAO.listar();
        DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
        model.setRowCount(0);

        for (Entrenador e : lista) {
            model.addRow(new Object[]{
                e.getIdEntrenador(),
                e.getNombreEntrenador(),
                e.getEspecialidad()
            });
        }
    } catch (Exception ex) {
        JOptionPane.showMessageDialog(this, "❌ Error al listar: " + ex.getMessage());
        ex.printStackTrace();
    }
}


