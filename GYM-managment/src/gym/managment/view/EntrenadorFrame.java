    private void GuardarButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_GuardarButtonActionPerformed
        try {
            String nombre = NombreTextField.getText();
            String especialidad = ActividadTextField.getText();

            if (nombre.isEmpty() || especialidad.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Todos los campos son obligatorios");
                return;
            }

            Entrenador e = new Entrenador();
            e.setNombreEntrenador(nombre);
            e.setEspecialidad(especialidad);

            entrenadorDAO.insertar(e);
            JOptionPane.showMessageDialog(this, "entrenador guardado correctamente");
            listarEntrenadores();

        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Error al guardar" + ex.getMessage());
            ex.printStackTrace();
        }
    }//GEN-LAST:event_GuardarButtonActionPerformed

